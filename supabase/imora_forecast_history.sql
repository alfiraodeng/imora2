-- Run once in the Supabase SQL Editor for the IMORA project.
-- Each refresh stores a forecast snapshot per monitored point for later comparison.
create table if not exists public.imora_forecast_history (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  scenario_name text not null,
  point_name text not null,
  latitude double precision not null,
  longitude double precision not null,
  captured_at timestamptz not null default now(),
  forecast_peak_at timestamptz,
  risk_level text not null,
  summary text not null,
  data jsonb not null default '{}'::jsonb
);

create index if not exists imora_forecast_history_owner_captured_idx
on public.imora_forecast_history (owner_id, captured_at desc);

create index if not exists imora_forecast_history_point_captured_idx
on public.imora_forecast_history (owner_id, latitude, longitude, captured_at desc);

alter table public.imora_forecast_history enable row level security;

drop policy if exists "imora_forecast_history_read_own" on public.imora_forecast_history;
create policy "imora_forecast_history_read_own"
on public.imora_forecast_history for select to authenticated
using (owner_id = auth.uid());

drop policy if exists "imora_forecast_history_insert_own" on public.imora_forecast_history;
create policy "imora_forecast_history_insert_own"
on public.imora_forecast_history for insert to authenticated
with check (owner_id = auth.uid());
