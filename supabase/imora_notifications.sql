-- Run once in the Supabase SQL Editor for the IMORA project.
create table if not exists public.imora_notifications (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  fingerprint text not null,
  category text not null default 'scenario',
  severity text not null,
  title text not null,
  detail text not null default '',
  data jsonb not null default '{}'::jsonb,
  is_dismissed boolean not null default false,
  dismissed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, fingerprint)
);

alter table public.imora_notifications enable row level security;

drop policy if exists "imora_notifications_read_own" on public.imora_notifications;
create policy "imora_notifications_read_own"
on public.imora_notifications for select to authenticated
using (owner_id = auth.uid());

drop policy if exists "imora_notifications_insert_own" on public.imora_notifications;
create policy "imora_notifications_insert_own"
on public.imora_notifications for insert to authenticated
with check (owner_id = auth.uid());

drop policy if exists "imora_notifications_update_own" on public.imora_notifications;
create policy "imora_notifications_update_own"
on public.imora_notifications for update to authenticated
using (owner_id = auth.uid())
with check (owner_id = auth.uid());
